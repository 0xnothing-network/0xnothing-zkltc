/**
 * English message catalog — the single source of truth for every user-facing
 * string in the wallet.
 *
 * `EN` is `as const`, so `MessageKey` is the union of its keys and a typo in a
 * `t()` call is a compile error rather than a blank label. Every other locale is
 * a `Partial` of the same keys (`Catalog` below): a missing entry falls back to
 * English instead of failing the build, which is what lets a translation land
 * one key at a time.
 *
 * Conventions
 *  - Placeholders are `{name}`, interpolated by `t()`. Same name, same meaning
 *    in every locale; a locale may reorder them freely.
 *  - Brand names, token symbols, addresses and hex stay untranslated and are
 *    passed in as parameters rather than baked into a string.
 *  - Button labels are written in sentence case here; `text-transform` in
 *    `wallet.css` decides how they are shown.
 */
